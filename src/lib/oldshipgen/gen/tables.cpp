void ShipTexture(ShipTex tx, float& s, float& t, float& u, float& v)
{
	const TextureSource source = CurrentTextureSource();
	if(source && source(tx, s, t, u, v))
		return;
	if(tx < 0 || tx >= ST_Count)
		tx = ST_Seat;
	s = ShipTexRect[tx].s; t = ShipTexRect[tx].t; u = ShipTexRect[tx].u; v = ShipTexRect[tx].v;
}

void EffectTexture(int tx, float& s, float& t, float& u, float& v)
{
	if(tx < 0 || tx >= EffectTexCount)
		tx = EffectTexCount - 1;
	s = EffectTexRect[tx].s; t = EffectTexRect[tx].t; u = EffectTexRect[tx].u; v = EffectTexRect[tx].v;
}

void WallProfile(int roomType, int style, std::vector<Vec3>& points, std::vector<int>& walls)
{
	points.clear();
	walls.clear();
	const Profile* p = Profiles[roomType & 0x1f];
	while(p->lastStyle < (style & 0xff))
		p++;
	for(int i = 0; i < p->points; i++)
		points.push_back(Vec3(p->out[i], 0, p->up[i]));
	for(int i = 0; i < p->walls; i++)
		walls.push_back(p->wall[i]);
}

